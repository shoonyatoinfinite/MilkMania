export type LanguageKey = 'en' | 'hi';

export const useTranslation = (lang: LanguageKey = 'en') => {
  const currentLang = (lang === 'hi' || lang === 'en') ? lang : 'en';
  const t = (key: keyof typeof translations['en']): string => {
    return (translations[currentLang] as any)?.[key] || (translations['en'] as any)?.[key] || String(key);
  };
  return { t, currentLang };
};

export default translations;
